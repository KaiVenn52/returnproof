import {loadPlaywright} from './browser-runtime.mjs';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
const {chromium}=loadPlaywright();
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();
const report={runAt:new Date().toISOString(),browser:await browser.version(),checks:[],errors:[]};
page.on('pageerror',e=>report.errors.push(e.message));
const pass=s=>{report.checks.push(s);console.log('PASS '+s);};
try {
  await page.goto('http://127.0.0.1:43178');
  assert.equal(await page.locator('#save-draft').isDisabled(),true);
  const action=await page.locator('.analyze').boundingBox();
  assert.ok(action.y+action.height<=1000);
  pass('Desktop first viewport contains the primary source action');
  await page.locator('#item').fill('Draft headphones');
  await page.locator('#receipt').fill('Delivered: 2026-10-10');
  await page.locator('#save-draft').click();
  assert.match(await page.locator('[data-case]').innerText(),/Draft/);
  await page.reload();await page.locator('[data-case]').click();
  assert.equal(await page.locator('#receipt').inputValue(),'Delivered: 2026-10-10');
  assert.equal(await page.locator('#deadline-value').count(),0);
  pass('Partial sources save and reopen as a draft without a calculated deadline');
  await page.locator('#policy').fill('Return requests within 30 calendar days of delivery, count from the day after delivery.');
  await page.locator('.analyze').click();
  assert.equal(await page.locator('#deadline-value').innerText(),'November 9, 2026');
  assert.equal(await page.locator('#calendar').isDisabled(),true);
  assert.equal(await page.locator('#save-draft').innerText(),'Save changes');
  await page.locator('#save-draft').click();
  await page.reload();await page.locator('[data-case]').click();
  assert.equal(await page.locator('#deadline-value').innerText(),'November 9, 2026');
  pass('Reopened draft can become a checked file and preserves the candidate after saving');
  await page.locator('#policy').fill('Return requests within 14 calendar days of delivery, count from the day after delivery.');
  await page.locator('#save-draft').click();await page.reload();await page.locator('[data-case]').click();
  assert.equal(await page.locator('#deadline-value').count(),0);
  await page.locator('.analyze').click();
  assert.equal(await page.locator('#deadline-value').innerText(),'October 24, 2026');
  await page.locator('#save-draft').click();
  pass('Saving changed sources and reopening cannot revive a stale candidate deadline');
  for(const id of ['merchant','item','receipt','policy'])await page.locator('#'+id).fill('');
  let prompted=false;page.once('dialog',async d=>{prompted=true;await d.dismiss();});
  await page.locator('#new').click();assert.equal(prompted,true);
  assert.equal(await page.locator('#receipt').inputValue(),'');
  assert.match(await page.locator('#draft-state').innerText(),/Unsaved/);
  pass('Clearing all source fields of a saved file still requires a discard decision');
  page.once('dialog',d=>d.accept());await page.locator('[data-case]').click();
  await page.setViewportSize({width:360,height:800});
  await page.getByRole('link',{name:'Return file',exact:true}).click();
  const nav=await page.locator('.workspace-toolbar').boundingBox();
  const heading=await page.locator('#plan-heading').boundingBox();
  assert.ok(heading.y>=nav.y+nav.height-1);
  assert.ok(heading.y<800);
  pass('Mobile return-file jump remains visible below the sticky navigation');
  const fault=await context.newPage();await fault.goto('http://127.0.0.1:43178');
  await fault.evaluate(()=>localStorage.setItem('returnproof.v1','{unreadable'));await fault.reload();
  await fault.getByRole('button',{name:/Try a clear example/}).click();await fault.locator('.analyze').click();
  await fault.locator('#delete').click();
  let recoveryPrompt='';fault.once('dialog',async d=>{recoveryPrompt=d.message();await d.dismiss();});
  await fault.locator('#delete').click();
  assert.match(recoveryPrompt,/replace that data/);
  assert.equal(await fault.evaluate(()=>localStorage.getItem('returnproof.v1')),'{unreadable');
  fault.once('dialog',d=>d.accept());await fault.locator('#delete').click();
  assert.equal(await fault.getByRole('alert').count(),0);
  assert.equal(await fault.evaluate(()=>localStorage.getItem('returnproof.v1')),'[]');
  pass('Deleting a fresh case cannot silently overwrite unreadable existing storage');
  await fault.close();assert.deepEqual(report.errors,[]);report.result='PASS';
} catch(e) {report.result='FAIL';report.error=e.stack;throw e;}
finally {await context.close();await browser.close();await writeFile('evidence/draft-review.json',JSON.stringify(report,null,2));}
